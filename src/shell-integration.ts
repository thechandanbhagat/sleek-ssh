export const COMMAND_HISTORY_OSC = 6973;
const BASH_PROMPT_ARRAY_MINIMUM_MAJOR_VERSION = 5;
const BASH_PROMPT_ARRAY_MINIMUM_MINOR_VERSION = 1;
const BASH_PS0_MINIMUM_MAJOR_VERSION = 4;
const BASH_PS0_MINIMUM_MINOR_VERSION = 4;

export const SSH_COMMAND_HISTORY_SCRIPT = [
  'if [ -z "${__SLEEKSSH_HISTORY_HOOK_INSTALLED-}" ] && command -v base64 >/dev/null 2>&1; then',
  '__sleekssh_history_command() {',
  'local __sleekssh_encoded;',
  '__sleekssh_encoded=$(printf \'%s\' "$1" | command base64 | command tr -d \'\\r\\n\') || return;',
  'printf \'\\033]6973;command;%s\\007\' "$__sleekssh_encoded";',
  '};',
  'if [ -n "${ZSH_VERSION-}" ]; then',
  '__sleekssh_history_started() { __sleekssh_history_command "$1"; printf \'\\033]6973;busy\\007\'; };',
  '__sleekssh_history_prompt() {',
  'case "$PS1" in *6973\\;prompt-start*) ;;',
  '*) PS1=$\'%{\\e]6973;prompt-start\\a%}\'"$PS1"$\'%{\\e]6973;prompt-end\\a%}\' ;; esac;',
  '};',
  'preexec_functions+=(__sleekssh_history_started);',
  'precmd_functions+=(__sleekssh_history_prompt);',
  'elif [ -n "${BASH_VERSION-}" ]; then',
  '__sleekssh_history_has_ps0=0;',
  `if (( BASH_VERSINFO[0] > ${BASH_PS0_MINIMUM_MAJOR_VERSION} || (BASH_VERSINFO[0] == ${BASH_PS0_MINIMUM_MAJOR_VERSION} && BASH_VERSINFO[1] >= ${BASH_PS0_MINIMUM_MINOR_VERSION}) )); then __sleekssh_history_has_ps0=1; fi;`,
  '__sleekssh_history_started() {',
  'local __sleekssh_entry __sleekssh_id __sleekssh_command;',
  '__sleekssh_entry=$(HISTTIMEFORMAT= builtin history 1);',
  'if [[ "$__sleekssh_entry" =~ ^[[:space:]]*([0-9]+)[\\ *][[:blank:]](.*)$ ]]; then',
  '__sleekssh_id=${BASH_REMATCH[1]};',
  'if [ "$__sleekssh_id" != "${__sleekssh_last_history_id-}" ]; then',
  '__sleekssh_command=${BASH_REMATCH[2]};',
  '__sleekssh_history_command "$__sleekssh_command";',
  'fi; fi;',
  'printf \'\\033]6973;busy\\007\';',
  '};',
  '__sleekssh_history_prompt() {',
  'local __sleekssh_status=$? __sleekssh_entry __sleekssh_id __sleekssh_command;',
  '__sleekssh_entry=$(HISTTIMEFORMAT= builtin history 1);',
  'if [[ "$__sleekssh_entry" =~ ^[[:space:]]*([0-9]+)[\\ *][[:blank:]](.*)$ ]]; then',
  '__sleekssh_id=${BASH_REMATCH[1]}; __sleekssh_command=${BASH_REMATCH[2]};',
  'if [ "$__sleekssh_history_has_ps0" = 0 ] && [ -n "${__sleekssh_last_history_id-}" ] && [ "$__sleekssh_id" != "$__sleekssh_last_history_id" ]; then __sleekssh_history_command "$__sleekssh_command"; fi;',
  '__sleekssh_last_history_id=$__sleekssh_id;',
  'fi;',
  'case "$PS1" in *6973\\;prompt-start*) ;;',
  '*) PS1=\'\\[\\e]6973;prompt-start\\a\\]\'"$PS1"\'\\[\\e]6973;prompt-end\\a\\]\' ;; esac;',
  'return "$__sleekssh_status";',
  '};',
  'if [ "$__sleekssh_history_has_ps0" = 1 ]; then PS0=\'$(__sleekssh_history_started)\'"${PS0-}"; fi;',
  `if (( BASH_VERSINFO[0] > ${BASH_PROMPT_ARRAY_MINIMUM_MAJOR_VERSION} || (BASH_VERSINFO[0] == ${BASH_PROMPT_ARRAY_MINIMUM_MAJOR_VERSION} && BASH_VERSINFO[1] >= ${BASH_PROMPT_ARRAY_MINIMUM_MINOR_VERSION}) )); then`,
  'PROMPT_COMMAND+=(__sleekssh_history_prompt);',
  'else PROMPT_COMMAND="${PROMPT_COMMAND-}"$\'\\n\'\'__sleekssh_history_prompt\'; fi;',
  'fi;',
  '__SLEEKSSH_HISTORY_HOOK_INSTALLED=1;',
  'fi',
].join(" ");
